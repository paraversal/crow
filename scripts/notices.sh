#!/usr/bin/env bash
# Regenerate THIRD-PARTY-NOTICES.md: every crate Crow links (macOS targets), grouped by
# licence text, plus the hand-written entries for non-crate material (icons, themes).
# Needs only cargo and python3. Usage: scripts/notices.sh [--check]
set -euo pipefail
cd "$(dirname "$0")/.."

out=THIRD-PARTY-NOTICES.md
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

{
  for t in aarch64-apple-darwin x86_64-apple-darwin; do
    cargo metadata --format-version 1 --filter-platform "$t" --locked 2>/dev/null > "$tmp.$t"
  done
  python3 -I - "$tmp.aarch64-apple-darwin" "$tmp.x86_64-apple-darwin" <<'PY'
import json, sys, os, glob, hashlib, collections

pkgs = {}
for path in sys.argv[1:]:
    m = json.load(open(path))
    ids = {n["id"] for n in m["resolve"]["nodes"]}
    for p in m["packages"]:
        if p["id"] in ids:
            pkgs[(p["name"], p["version"])] = p

root = os.getcwd()
def is_ours(p):
    d = os.path.dirname(p["manifest_path"])
    return d.startswith(os.path.join(root, "crates"))

def licence_files(p):
    d = os.path.dirname(p["manifest_path"])
    names = []
    for pat in ("LICENSE*", "LICENCE*", "COPYING*", "UNLICENSE*", "NOTICE*"):
        names += glob.glob(os.path.join(d, pat))
    # Zed's workspace crates keep theirs in the repository root.
    if not names and os.path.join(root, "vendor") in d:
        names += glob.glob(os.path.join(root, "vendor", "zed", "LICENSE-*"))
    return sorted({n for n in names if os.path.isfile(n)})

groups = collections.OrderedDict()  # text hash -> (text, [crates])
nofile = []
for (name, ver), p in sorted(pkgs.items()):
    if is_ours(p):
        continue
    files = licence_files(p)
    if not files:
        nofile.append((name, ver, p.get("license") or "unknown"))
        continue
    for f in files:
        text = open(f, encoding="utf-8", errors="replace").read().strip()
        h = hashlib.sha256(text.encode()).hexdigest()
        groups.setdefault(h, (text, []))[1].append(f"{name} {ver}")

print("# Third-party notices\n")
print("Crow is licensed under GPL-3.0-or-later (see `LICENSE`). It includes the following")
print("third-party material. This file is generated by `scripts/notices.sh`; do not edit it by hand.\n")
print("## Icons, themes and fonts\n")
print("- **Lucide icons**: ISC licence (and MIT for the Feather portions). Full text in `Lucide-LICENSE.txt`. https://lucide.dev")
print("- **Built-in theme palettes**: Catppuccin (MIT), Gruvbox (MIT), Solarized (MIT); Finder Light/Dark are Crow's own. Sources and licences are listed in `crates/crow-theme/themes/NOTICE.md`.")
print("- **App icons**: Crow's own artwork, GPL-3.0-or-later with the rest of the project.\n")
print("## Rust crates\n")
print(f"{sum(len(c) for _, c in groups.values())} licence files across {len(pkgs)} crates. Crates that share a licence text are grouped.\n")
for text, crates in sorted(groups.values(), key=lambda g: -len(g[1])):
    print("### Used by: " + ", ".join(sorted(set(crates))) + "\n")
    print("```text\n" + text + "\n```\n")
if nofile:
    print("## Crates without a licence file in their package\n")
    print("Their licence is declared in `Cargo.toml` and is compatible with GPL-3.0-or-later.\n")
    for n, v, l in nofile:
        print(f"- {n} {v}: {l}")
PY
} > "$tmp"

if [ "${1:-}" = "--check" ]; then
  diff -q "$tmp" "$out" >/dev/null || { echo "$out is out of date: run scripts/notices.sh" >&2; exit 1; }
else
  cp "$tmp" "$out"
  echo "wrote $out ($(wc -c < "$out" | tr -d ' ') bytes)"
fi
